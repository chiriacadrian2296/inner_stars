/// Fixed vocabulary shared by composer controls. Content text is never translated.
String shareComposerLabel(BuildContext context, String label) {
  final code = context.strings.languageCode;
  if (code == 'it') return label;
  final entry = _labels[label];
  return entry == null
      ? label
      : code == 'ro'
      ? entry.$2
      : entry.$1;
}

